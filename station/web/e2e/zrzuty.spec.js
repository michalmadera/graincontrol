// Zrzuty wszystkich ekranów w 1280 × 800: uruchamiane tylko z ZRZUTY=<katalog>.
import { test, expect } from '@playwright/test'
import { reset, przyciskGlowny, SERWIS } from './pomoc.js'

const katalog = process.env.ZRZUTY
test.skip(!katalog, 'Ustaw ZRZUTY=<katalog>')

test('zrzuty', async ({ page, request }) => {
  test.setTimeout(120_000)
  const zrzut = (n) => page.screenshot({ path: `${katalog}/${n}.png` })
  const naglowek = (t) => expect(page.getByRole('heading', { name: t })).toBeVisible()
  await reset(request)
  await request.post('/api/dev/ustawienia', { data: { czas_splywu_s: 150 } })
  await page.goto('/')
  await naglowek('Potrzebna kalibracja'); await zrzut('02-kalibracja')
  await przyciskGlowny(page, 'KALIBRACJA')
  await naglowek('Trwa kalibracja'); await zrzut('02b-kalibracja-trwa')
  await naglowek('Maszyna gotowa'); await zrzut('03-gotowa')
  await przyciskGlowny(page, 'NOWY POMIAR')
  await naglowek('Wsyp próbkę do lejka'); await zrzut('05-wsyp')
  await przyciskGlowny(page, 'PRÓBKA WSYPANA')
  await naglowek('Kamyki spływają'); await zrzut('06-splyw')
  await naglowek('Maszyna rozgarnia próbkę'); await zrzut('07-rozgarnianie')
  await naglowek('Analizuję…'); await zrzut('09-analiza')
  await naglowek(/DOBRA|ZŁA/); await zrzut('10-wynik')
  await przyciskGlowny(page, 'DALEJ')
  await naglowek('Maszyna czyści stół'); await zrzut('11-czyszczenie')
  await naglowek('Opróżnij pudełko na kamyki'); await zrzut('12-pudelko')
  await przyciskGlowny(page, 'OPRÓŻNIONE')
  await naglowek('Maszyna gotowa'); await zrzut('03b-gotowa-z-wynikami')
  await page.getByRole('button', { name: 'STOP' }).click()
  await naglowek('Maszyna zatrzymana'); await zrzut('zatrzymana')
  await reset(request)
  await page.reload()
  await page.getByTestId('logo').hover()
  await page.mouse.down(); await page.waitForTimeout(5200); await page.mouse.up()
  await naglowek('Tryb serwisowy'); await page.waitForTimeout(500); await zrzut('serwis')
  await reset(request)
  await request.post(`${SERWIS}/api/dev/wymus`, { data: {} })
  await page.reload()
  await request.post('/api/dev/blad', { data: { makro: 'KALIBRUJ', tresc: 'INTERLOCK' } })
  await przyciskGlowny(page, 'KALIBRACJA')
  await naglowek('Wystąpił błąd'); await zrzut('blad')
})
